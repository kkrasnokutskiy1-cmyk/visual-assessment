import type { Block, Option, Question, Reference } from "@/lib/assessment/types";
import { interactionReferences } from "@/content/research/interaction";

const ref = (id: string): Reference => {
  const found = interactionReferences.find((item) => item.id === id);
  if (!found) throw new Error(`Unknown interaction reference: ${id}`);
  return found;
};

const options = (...labels: string[]): Option[] =>
  labels.map((label, i) => ({ id: String.fromCharCode(97 + i), label }));

type Draft = Omit<Question, "version" | "allowComment" | "source" | "refId" | "asset" | "interpretation"> & {
  reference: Reference;
  answer: string;
  observation: string;
  explanations: string[];
  alternatives: string[];
};

const question = ({ reference, answer, observation, explanations, alternatives, ...draft }: Draft): Question => ({
  ...draft,
  version: 1,
  allowComment: true,
  refId: reference.id,
  asset: reference.figures.single,
  source: {
    title: reference.title,
    url: reference.url,
    author: reference.author,
    publisher: reference.publisher,
    publishedAt: reference.publishedAt,
    license: "Первоисточник; права на изображение не подтверждены",
  },
  interpretation: {
    observation: `По источнику ближе вариант ${answer}. ${observation}`,
    explanations,
    alternatives,
  },
});

